namespace System\Base\Installer\Components\Setup;

/**
 * Encapsulates installer progress steps and stage registration.
 */
class ProgressManager
{
    /**
     * Progress service instance.
     *
     * @var mixed
     */
    protected mixed $progress;

    /**
     * ProgressManager constructor.
     *
     * @param mixed $progress Progress service instance.
     */
    public function __construct(mixed $progress)
    {
        $this->progress = $progress;
    }

    /**
     * Registers installation stages with progress tracker.
     *
     * @return void
     */
    public function registerProgressMethods(): void
    {
        $this->progress->registerMethods([
            ['method' => 'createNewDb', 'text' => 'Creating new database...'],
            ['method' => 'createNewUser', 'text' => 'Checking database user...'],
            ['method' => 'checkDbEmpty', 'text' => 'Checking if db is empty...'],
            ['method' => 'buildSchema', 'text' => 'Building database schema...'],
            ['method' => 'registerRepos', 'text' => 'Registering repositories...'],
            ['method' => 'registerDomain', 'text' => 'Registering domain...'],
            ['method' => 'writeBaseConfigs', 'text' => 'Writing base configurations...'],
            ['method' => 'registerCore', 'text' => 'Registering core...'],
            ['method' => 'registerCoreAppType', 'text' => 'Registering core app type...'],
            ['method' => 'registerCoreApp', 'text' => 'Registering core app...'],
            ['method' => 'registerModule', 'text' => 'Registering components modules...'],
            ['method' => 'updateCoreAppComponents', 'text' => 'Updating core app components...'],
            ['method' => 'registerModule', 'text' => 'Registering packages modules...'],
            ['method' => 'registerModule', 'text' => 'Registering middlewares modules...'],
            ['method' => 'registerModule', 'text' => 'Registering views modules...'],
            ['method' => 'registerModule', 'text' => 'Registering external modules...'],
            ['method' => 'registerCoreRole', 'text' => 'Registering core role...'],
            ['method' => 'registerCoreAccount', 'text' => 'Registering core account...'],
            ['method' => 'registerCoreProfile', 'text' => 'Registering core profile...'],
            ['method' => 'registerAdditionalRoles', 'text' => 'Registering additional roles...'],
            ['method' => 'registerExcludeAutoGeneratedFilters', 'text' => 'Registering filters...'],
            [
                'method' => 'processGeoData',
                'text'   => 'Processing geo location...',
                'childs' => [
                    ['method' => 'registerCountries', 'text' => 'Registering geo location: countries...'],
                    ['method' => 'registerTimezones', 'text' => 'Registering timezones...'],
                ]
            ],
            ['method' => 'registerWorkers', 'text' => 'Registering workers...'],
            ['method' => 'registerSchedules', 'text' => 'Registering schedules...'],
            ['method' => 'registerTasks', 'text' => 'Registering tasks...'],
            ['method' => 'performIndexing', 'text' => 'Indexing Database...'],
            ['method' => 'cleanVar', 'text' => 'Cleaning variable directory...'],
            ['method' => 'cleanOldBackups', 'text' => 'Cleaning old backups...'],
            ['method' => 'cleanOldCookies', 'text' => 'Cleaning old cookies...'],
            ['method' => 'writeConfigs', 'text' => 'Writing configurations...'],
        ]);
    }
}
